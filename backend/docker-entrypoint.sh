#!/usr/bin/env sh
set -e

# Контейнер стартует от root (см. Dockerfile — USER там намеренно не
# зафиксирован), чтобы каждый раз при старте самостоятельно чинить
# владельца примонтированного с хоста backend/uploads под appuser
# (10001:10001, см. Dockerfile) — bind mount на каждом старте перекрывает
# собой то, что было прописано в образе на этапе сборки, и после первого
# перехода на непривилегированный контейнер каталог на хосте/в dev-checkout
# ещё принадлежит старому владельцу. Раньше это был отдельный ручной шаг
# в deploy/README.md ПЕРЕД `up -d` — ненадёжно: (1) легко перепутать
# порядок и обратиться уже после первого падающего аплоада, (2) деплой по
# кнопке (deploy-watcher.sh) о нём вообще не знал и просто не выполнял. Раз
# уже в entrypoint — самовосстанавливается при каждом старте контейнера,
# для любого пути деплоя (ручной SSH, deploy-watcher.sh, dev docker-compose).
chown -R appuser:appgroup /app/uploads

# БД может быть ещё не готова принимать соединения сразу после старта её
# контейнера (в dev-compose у depends_on нет condition: service_healthy) —
# несколько попыток с паузой вместо мгновенного падения контейнера api.
i=0
until alembic upgrade head; do
  i=$((i + 1))
  if [ "$i" -ge 10 ]; then
    echo "alembic upgrade head: не удалось после $i попыток" >&2
    exit 1
  fi
  echo "БД ещё не готова, повтор через 3с ($i/10)..." >&2
  sleep 3
done

# --forwarded-allow-ips '*' — без этого uvicorn доверяет X-Forwarded-Proto/Host
# только от 127.0.0.1 (свой дефолт), а nginx подключается по внутренней
# docker-сети со своим IP контейнера; без доверия эти заголовки игнорируются,
# и request.url в pdf_report.py собирается как http://<внутренний хост>:8000
# вместо реального https://.../ :8443 — там на это завязаны ссылки на фото.
# Безопасно: порт api не публикуется наружу в проде (см. docker-compose.prod.yml) —
# достучаться до него может только proxy-контейнер той же сети.
#
# setpriv (util-linux, essential-пакет Debian — есть в любом образе на его
# основе без доп. установки) заменяет ТЕКУЩИЙ процесс на uvicorn от
# appuser, а не оборачивает его ещё одним процессом поверх (как su/sudo) —
# uvicorn становится PID 1 самим собой, сигналы (SIGTERM на docker stop)
# доходят напрямую, без риска, что их поглотит промежуточная обёртка.
# Миграции выше намеренно остаются от root — они не пишут на диск, только
# по сети в БД, и не обрабатывают пользовательский ввод.
exec setpriv --reuid=appuser --regid=appgroup --init-groups \
  uvicorn app.main:app --host 0.0.0.0 --port 8000 --forwarded-allow-ips '*'
