function normalize(text: string): string {
  return text.toLocaleLowerCase('ru').replace(/ё/g, 'е')
}

/** Все слова запроса должны встретиться в вопросе или ответе (регистр и ё/е
 * не важны) — фраза целиком почти никогда не совпадает дословно из-за
 * падежей («сброс пароля» vs «сбросить пароль»). */
export function filterFaq(topics: FaqTopic[], role: FaqRoleFilter, query: string): FaqTopic[] {
  const words = normalize(query).split(/\s+/).filter(Boolean)
  return topics
    .map((topic) => ({
      ...topic,
      items: topic.items.filter((item) => {
        if (role !== 'all' && !item.roles.includes(role)) return false
        if (words.length === 0) return true
        const haystack = normalize(`${item.q} ${item.a}`)
        return words.every((word) => haystack.includes(word))
      }),
    }))
    .filter((topic) => topic.items.length > 0)
}
